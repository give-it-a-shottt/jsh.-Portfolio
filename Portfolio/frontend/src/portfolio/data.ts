/** Design 사례의 화면 한 장(시안·화면 구성·디자인 시스템 가이드) */
export interface DesignVariant {
  label: string
  image: string
  /** 이 안에서 바꾼 점·이유, 또는 이 화면이 하는 일 한 줄 */
  note: string
  /** 이미지 원본 크기. 없으면 400×860 휴대폰 시안으로 본다 */
  width?: number
  height?: number
}

/** 제목을 직접 붙인 화면 묶음 한 칸 — 디자인 시스템처럼 페이지가 많아 분류별로 나눠 보여줄 때 쓴다 */
export interface DesignSection {
  title: string
  description: string
  items: DesignVariant[]
  /** 없으면 데스크톱 카드 */
  device?: 'mobile' | 'desktop'
}

/**
 * Design 사례 — 같은 화면을 여러 안으로 고친 과정(variants), 또는 앱 전체 화면 구성(screens)과
 * 디자인 시스템(system). 대표 화면은 실제 동작하는 데모로 함께 보여준다(demos/index.ts).
 */
export interface DesignCase {
  /** 어떤 서비스의 화면인지 */
  app: string
  /** 시안 화면 종류. 없으면 휴대폰 화면으로 본다 */
  device?: 'mobile' | 'desktop'
  /** 처음 시안에서 느낀 문제, 또는 설계하며 풀려던 문제 */
  problem: string
  /** 참여 범위와 기여도. 있으면 상단 요약에 '참여' 줄로 보여준다 */
  role?: string
  /** 분류별 화면 묶음. 있으면 맨 앞 칸부터 순서대로 보여준다 */
  sections?: DesignSection[]
  /** 케이스 스터디 장표(16:9). 있으면 맨 앞 칸에 보여준다 */
  story?: DesignVariant[]
  /** 같은 화면을 고쳐 나간 시안 */
  variants?: DesignVariant[]
  /** variants 중 최종안의 위치 */
  finalIndex?: number
  /** 앱의 주요 화면 */
  screens?: DesignVariant[]
  /** screens 가 데스크톱일 때 따로 모은 모바일 화면 */
  mobileScreens?: DesignVariant[]
  /** 디자인 시스템 가이드(컬러·타이포·컴포넌트). 넓고 긴 문서라 device 와 상관없이 데스크톱 카드로 보여준다 */
  system?: DesignVariant[]
  /** system 칸의 제목·설명. 없으면 '디자인 시스템'. IA·플로우만 있는 사례처럼 내용이 다를 때 쓴다 */
  systemHeading?: { title: string; description: string }
  /** 실제 동작 화면 칸의 제목·설명. 데모가 등록된 사례에만 쓴다 */
  demo?: { title: string; note: string; caveat?: string }
}

export interface PortfolioCase {
  slug: string
  type: CaseType
  code: string
  date: string
  /** 중요도 1~4 — 높은 것부터 보여준다. 화면에는 보이지 않는다(기준은 rank.ts) */
  level: Level
  title: string
  description: string
  metrics: { label: string; value: string }[]
  tags: string[]
  /** 화면에 보이지 않는 추가 검색어 */
  keywords: string
  /** Front 썸네일. 없으면 자리표시 이미지(assets/screenshot-placeholder.webp)를 보여준다 */
  image?: string
  /** 눌렀을 때 갈 곳 — 보통 사례 상세 `#/case/{slug}`. 없으면 링크 없이 보여준다 */
  href?: string
  /** href 말고 따로 열어볼 곳(실제 화면, 이전 버전 등). 새 탭으로 연다 */
  links?: { label: string; href: string }[]
  /** type 이 'Design' 인 사례의 시안 비교 */
  design?: DesignCase
}

